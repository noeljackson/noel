    #[test]
    fn the_store_loads_its_snapshot_and_reports_writes() {
        let mut store = BTreeMap::new();
        store.insert("seen".to_owned(), "3".to_owned());
        let run = run_with(
            "store('next', { n: load('seen') + 1 }); store('seen', undefined); return load('next');",
            store,
            Arc::default(),
        );
        let Some(VmMessage::Done { value, writes }) = &run.end else {
            panic!("{:?}", run.end);
        };
        assert_eq!(value.as_deref(), Some("{\"n\":4}"));
        let writes: serde_json::Value = serde_json::from_str(writes).unwrap();
        assert_eq!(writes, json!([["next", "{\"n\":4}"], ["seen"]]));
    }

    #[test]
    fn an_interrupt_stops_a_spinning_script() {
        let interrupt = Arc::new(AtomicBool::new(false));
        let flag = interrupt.clone();
        let stopper = std::thread::spawn(move || {
            std::thread::sleep(Duration::from_millis(200));
            flag.store(true, Ordering::Relaxed);
        });
        let run = run_with("while (true) {}", BTreeMap::new(), interrupt);
        stopper.join().unwrap();
        assert_eq!(
            run.end,
            Some(VmMessage::Crash {
                message: "Execution interrupted".to_owned()
            })
        );
    }


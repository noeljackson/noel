    #[test]
    fn the_vendored_prelude_is_upstreams() {
        // FNV-1a over UTF-16 code units, as djs fingerprints the prelude. A
        // changed prelude must come from the fixture script, not an edit.
        let mut hash: u32 = 0x811c_9dc5;
        for unit in PRELUDE_SOURCE.encode_utf16() {
            hash ^= u32::from(unit);
            hash = hash.wrapping_mul(0x0100_0193);
        }
        let pinned: serde_json::Value =
            serde_json::from_str(include_str!("vendor/prelude.json")).unwrap();
        assert_eq!(
            pinned["source"]["commit"],
            "7dc38ff0e9490483b368c2b14531c9199c4cbee1"
        );
        assert_eq!(format!("{hash:08x}"), PRELUDE_FNV1A);
    }

